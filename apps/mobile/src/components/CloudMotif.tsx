/**
 * Үүлэн хээ — зориудаар зохиосон нэгж чимэглэл
 *
 * ══ ДӨРВӨН БҮТЭЛГҮЙ ОРОЛДЛОГЫН ДАРААХ ДҮГНЭЛТ ══
 *
 * Өмнөх бүх хувилбар үүлийг ДАВТАГДАХ НУМАН ЭГНЭЭ гэж барьсан. Өнгө нь
 * зөв болсон ч хэлбэр нь эцсээ хүртэл «майхны хаяавч» шиг хэвээр байв.
 *
 * Лавлах зургуудыг нягтлахад жинхэнэ бүтэц өөр болох нь тодорхой болов:
 *
 *   1. НЭГЖ НЬ НУМ БИШ, МУШГИА. Дэлбээ бүр нь тойрог бөгөөд дотроо
 *      төвлөрсөн цагираг үүсгэн ороодог — «ороосон» мэдрэмж эндээс.
 *   2. ЭГНЭДЭГГҮЙ, БӨӨГНӨРДӨГ. Том дэлбээ голдоо, жижгүүд нь тойрон
 *      багцлагдана. Жигд эгнээ бол механик.
 *   3. ДЭЛБЭЭ БҮР ӨӨР ӨНГӨТЭЙ. Индиго, фирүүз, шар, шүр, ногоон
 *      зэрэгцэн оршино.
 *   4. ЦАГААН ХАЛО бүх массыг хүрээлнэ — өнгө хоорондоо шингэхээс
 *      сэргийлнэ.
 *   5. УРСГАЛ СҮҮЛ хажуугаас нь гарна.
 *
 * ══ ЗУРААСНЫ ДАРААЛАЛ (чухал) ══
 *
 * Бүх ХАЛО эхэлж, дараа нь бүх БИЕ, эцэст нь бүх ЦАГИРАГ. Дэлбээ тус
 * бүрээр гурвууланг зурвал хөрш дэлбээний хало нь өмнөхийнхөө биеийг
 * зүсэж, гинжин цагаан зураас үүсгэдэг.
 */
import React, { useMemo } from 'react';
import { View, type StyleProp, type ViewStyle } from 'react-native';
import Svg, { Circle, ClipPath, Defs, G, Path } from 'react-native-svg';
import { colors } from '@/theme';

type Lobe = { x: number; y: number; r: number; c: number };

/**
 * Гараар байрлуулсан дэлбээ. Процедураар үүсгэвэл жигд болж механик
 * харагддаг тул зориудаар тэгш хэмгүй байрлуулав.
 *
 * `c` нь өнгөний индекс — зэргэлдээ дэлбээ ижил өнгөтэй болохоос сэргийлж
 * гараар сонгосон.
 */
const LOBES: Lobe[] = [
  // Гол бөөгнөрөл — радиусын НИЙЛБЭР нь төв хоорондын зайнаас ИХ байх
  // ёстой. Эс тэгвээс дэлбээ нийлж масс болохгүй, тусдаа диск шиг харагдана.
  { x: 100, y: 44, r: 32, c: 0 },
  { x: 74, y: 50, r: 26, c: 1 },
  { x: 128, y: 49, r: 27, c: 0 },
  { x: 88, y: 26, r: 21, c: 2 },
  { x: 118, y: 25, r: 19, c: 1 },
  // Хажуу тийш багасна
  { x: 52, y: 56, r: 20, c: 3 },
  { x: 150, y: 55, r: 19, c: 1 },
  { x: 34, y: 60, r: 14, c: 0 },
  { x: 168, y: 60, r: 13, c: 4 },
  { x: 62, y: 32, r: 14, c: 1 },
  { x: 142, y: 31, r: 13, c: 0 },
];

/** Урсгал сүүл — массаас хоёр тийш гарна */
const TAILS = [
  'M26 74 C14 80, 6 78, 2 72 C7 76, 15 75, 22 70',
  'M184 73 C196 79, 205 77, 210 71 C205 75, 196 74, 189 69',
];

/**
 * ⚠ Лавлах зурагт өнгө нь ТЭНЦҮҮ хуваарилагддаггүй: индиго ба фирүүз
 * массын 70%-ийг эзэлж, шар/шүр нь цөөн дэлбээнд өргөлт болж ордог.
 * Тэнцүү хуваавал конфетти болно.
 */
const PALETTE = [
  colors.ink.indigo, // 0 — давамгай
  colors.ink.teal, // 1 — давамгай
  colors.gold, // 2 — өргөлт
  colors.ink.coral, // 3 — өргөлт
  colors.primary, // 4 — ховор өргөлт
];

/**
 * Архимедийн мушгиа — дэлбээний цөм.
 *
 * ⚠ ГОЛ ЗАСВАР: өмнө нь ТӨВЛӨРСӨН ЦАГИРАГ зурдаг байсан. Тэр нь буудлагын
 * «бай» шиг харагддаг — үүлэн хээний мэдрэмж огт өгөхгүй. Лавлах зурагт
 * дэлбээ бүрийн дотор нь ЭРГЭЛДЭН ДОТОГШОО ОРООСОН нэг тасралтгүй муруй
 * байна. Тэр мушгиа нь үүлэн хээг үүлэн хээ болгодог цорын ганц шинж.
 *
 * r(t) шугаман багасаж, θ(t) нь `turns` эргэлт хийнэ.
 */
function spiralPath(
  cx: number,
  cy: number,
  rOuter: number,
  rInner: number,
  turns: number,
  startAngle: number
): string {
  const STEPS = 44;
  let d = '';
  for (let i = 0; i <= STEPS; i++) {
    const t = i / STEPS;
    const r = rOuter + (rInner - rOuter) * t;
    const a = startAngle + t * turns * Math.PI * 2;
    const x = cx + r * Math.cos(a);
    const y = cy + r * Math.sin(a);
    d += `${i === 0 ? 'M' : 'L'}${x.toFixed(1)} ${y.toFixed(1)} `;
  }
  return d.trim();
}

export function CloudMotif({
  width = 210,
  /** Толин тусгал — эсрэг буланд тавихад */
  flip = false,
  opacity = 1,
  /** Цагаан халогийн зузаан */
  halo = 7,
  style,
}: {
  width?: number;
  flip?: boolean;
  opacity?: number;
  halo?: number;
  style?: StyleProp<ViewStyle>;
}) {
  const VB_W = 212;
  const VB_H = 92;
  const height = (width / VB_W) * VB_H;

  /** Дэлбээ бүрийн мушгиа. Эхлэх өнцгийг ялгаварлаж жигд байдлыг эвднэ */
  const spirals = useMemo(
    () =>
      LOBES.map((l, i) => ({
        l,
        /**
         * ⚠ ГОЛ ЗАСВАР: мушгиаг НИМГЭН зураасаар зурахад дэлбээн дээр
         * хаясан утас шиг харагдана. Лавлах зурагт мушгиа нь ӨРГӨН ТУУЗ:
         * өнгөт дэлбээ дээр өргөн ЦАГААН мушгиа зурахад өнгө нь цагаанаар
         * тусгаарлагдсан цагирган туузууд болж хуваагдана. Яг тэр л
         * «ороосон» мэдрэмжийг өгдөг.
         *
         * Тиймээс зузаан нь радиусын ~18% байх ёстой, 11% биш.
         *
         * ⚠ 30% нь хэтэрсэн: цагаан нь өнгийг даран дэлбээ бүр цагаан
         * болж хувирдаг. Лавлахад ӨНГӨ давамгайлж, цагаан нь зөвхөн
         * тусгаарлагч. 18% нь тэнцвэрийг олно.
         */
        d: spiralPath(l.x, l.y, l.r * 0.82, l.r * 0.12, 1.35, (i * 2.4) % (Math.PI * 2)),
        w: l.r * 0.18,
      })),
    []
  );

  return (
    <View style={style} pointerEvents="none">
      <Svg width={width} height={height} viewBox={`0 0 ${VB_W} ${VB_H}`} opacity={opacity}>
        <Defs>
          {LOBES.map((l, i) => (
            <ClipPath key={`cp${i}`} id={`lobe${i}`}>
              <Circle cx={l.x} cy={l.y} r={l.r} />
            </ClipPath>
          ))}
        </Defs>

        <G transform={flip ? `translate(${VB_W},0) scale(-1,1)` : undefined}>
          {/* 1. Бүх ХАЛО эхэлнэ — эс тэгвээс хөрш дэлбээний хало биеийг зүснэ */}
          <G fill={colors.ink.halo}>
            {TAILS.map((d, i) => (
              <Path key={`th${i}`} d={d} stroke={colors.ink.halo} strokeWidth={halo + 3} fill="none" />
            ))}
            {LOBES.map((l, i) => (
              <Circle key={`h${i}`} cx={l.x} cy={l.y} r={l.r + halo} />
            ))}
          </G>

          {/* 2. Бүх БИЕ */}
          {TAILS.map((d, i) => (
            <Path
              key={`tb${i}`}
              d={d}
              stroke={PALETTE[i % PALETTE.length]}
              strokeWidth={halo}
              strokeLinecap="round"
              fill="none"
            />
          ))}
          {LOBES.map((l, i) => (
            <Circle key={`b${i}`} cx={l.x} cy={l.y} r={l.r} fill={PALETTE[l.c % PALETTE.length]} />
          ))}

          {/*
            3. ЦАГИРАГ — дэлбээ бүрд ӨӨРИЙНХӨӨ хүрээнд хашина.

            ⚠ Хашилтгүй үед А дэлбээний цагираг Б дэлбээний бие рүү халин
            орж, бүхэл масс дээр эмх замбараагүй тор үүсгэдэг байв. Энэ нь
            «мушгиа» биш «хаясан цагираг» шиг харагдана. Лавлах зурагт
            цагираг бүр өөрийн дэлбээнээсээ ХЭЗЭЭ Ч халихгүй.
          */}
          {spirals.map(({ d, w }, i) => (
            <G key={`sp${i}`} clipPath={`url(#lobe${i})`}>
              <Path
                d={d}
                fill="none"
                stroke={colors.ink.halo}
                strokeWidth={w}
                strokeLinecap="round"
                opacity={0.95}
              />
            </G>
          ))}
        </G>
      </Svg>
    </View>
  );
}
